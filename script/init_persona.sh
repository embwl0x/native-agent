#!/usr/bin/env bash
# script/init_persona.sh — Phase 11: first-run persona initializer.
#
# Called by install_app.sh before launching NativeAgent.app so new
# cloners get working persona docs from the bundled templates. USER.md is
# generated from MemoryV2, not copied from a template.
#
# Behavior (idempotent — safe to re-run):
#   1. If persona/SOUL.md is absent, copy persona/SOUL.template.md → persona/SOUL.md
#   2. Create absent AGENTS/GROWTH from their templates; preserve existing bytes.
#   3. Ensure data/ exists (mkdir -p)
#   4. Ensure workspace/ exists (mkdir -p) — Phase 11b
#   5. Empty/unreadable existing documents or unavailable required templates fail setup.

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PERSONA_DIR="$ROOT/persona"
DATA_DIR="$ROOT/data"
WORKSPACE_DIR="$ROOT/workspace"

_log() { echo "[init_persona] $*"; }

# Publish a complete new file without ever replacing an existing directory entry.
_create_from_template() {
    local name="$1" src="$PERSONA_DIR/$1.template.md" dst="$PERSONA_DIR/$1.md"
    if [ -e "$dst" ] || [ -L "$dst" ]; then
        if [ ! -f "$dst" ] || [ ! -r "$dst" ] || [ ! -s "$dst" ]; then
            _log "ERROR: $dst exists but is empty, unreadable or not a regular file. Preserving it; repair the authored document."
            return 1
        fi
        _log "persona/$name.md already exists — preserving it."
        return
    fi
    if [ ! -f "$src" ] || [ ! -r "$src" ] || [ ! -s "$src" ]; then
        _log "ERROR: required genesis template $src is missing, empty or unreadable."
        return 1
    fi
    local tmp
    tmp="$(mktemp "$PERSONA_DIR/.$name.genesis.XXXXXX")"
    if ! cp "$src" "$tmp"; then
        rm "$tmp"
        return 1
    fi
    if ! /bin/link "$tmp" "$dst"; then
        rm "$tmp"
        _log "ERROR: could not create $dst without replacing existing content."
        return 1
    fi
    rm "$tmp"
    _log "Created persona/$name.md from template."
}

_create_from_template SOUL
_create_from_template AGENTS
_create_from_template GROWTH

# USER.md is generated by MemoryV2; setup never copies a user template.
_log "persona/USER.md belongs to MemoryV2 — preserving any existing document."

# 3. data/ directory
if [ ! -d "$DATA_DIR" ]; then
    mkdir -p "$DATA_DIR"
    _log "Created data/ directory."
else
    _log "data/ already exists — skipping."
fi

# 4. workspace/ directory (Phase 11b)
if [ ! -d "$WORKSPACE_DIR" ]; then
    mkdir -p "$WORKSPACE_DIR"
    touch "$WORKSPACE_DIR/.gitkeep"
    _log "Created workspace/ directory."
else
    _log "workspace/ already exists — skipping."
fi

echo
echo "Setup complete."
echo "  Edit persona/SOUL.md to define your agent's identity."
echo "  persona/USER.md is generated from memory SQLite; save durable user facts through memory."
echo "  Runtime state will be written to data/ (gitignored)."
echo "  Work product (drafts, exports, scratch) goes in workspace/ (gitignored)."
