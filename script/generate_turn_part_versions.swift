#!/usr/bin/env swift
import CryptoKit
import Foundation

let arguments = Array(CommandLine.arguments.dropFirst())
let check = arguments.contains("--check")
let repoIndex = arguments.firstIndex(of: "--repo")
let repo = URL(fileURLWithPath: repoIndex.map { arguments[$0 + 1] } ?? FileManager.default.currentDirectoryPath)
let source = "Resources/abilities/turn.js"
let destination = repo.appendingPathComponent("Modules/NativeAgentCore/Sources/ChatTurnRuntime/TurnPart+ShippedBodies.swift")

// Source archives compile the committed table; regeneration requires full history.
if !FileManager.default.fileExists(atPath: repo.appendingPathComponent(".git").path) {
    _ = try Data(contentsOf: destination)
    print("[turn versions] source archive uses the committed generated table")
    exit(0)
}

func git(_ arguments: [String]) throws -> Data {
    let task = Process()
    task.executableURL = URL(fileURLWithPath: "/usr/bin/git")
    task.arguments = ["-C", repo.path] + arguments
    let output = Pipe()
    task.standardOutput = output
    try task.run()
    let bytes = output.fileHandleForReading.readDataToEndOfFile()
    task.waitUntilExit()
    guard task.terminationStatus == 0 else { fatalError("git failed: \(arguments)") }
    return bytes
}

// Match AbilityStore.decode and File.digest: SHA256 of UTF-8 body bytes after
// the exact header delimiter, excluding the NativeAgent ability comment.
func identity(_ bytes: Data) throws -> (version: Int64, digest: String) {
    let start = "/* NativeAgent ability\n", end = "\n*/\n"
    guard let text = String(data: bytes, encoding: .utf8), text.hasPrefix(start),
          let boundary = text.range(of: end, range: text.index(text.startIndex, offsetBy: start.count)..<text.endIndex) else {
        fatalError("invalid committed turn ability envelope")
    }
    struct Header: Decodable { let version: Int64 }
    let header = try JSONDecoder().decode(Header.self, from: Data(text[text.index(text.startIndex, offsetBy: start.count)..<boundary.lowerBound].utf8))
    let body = Data(text[boundary.upperBound...].utf8)
    return (header.version, SHA256.hash(data: body).map { String(format: "%02x", $0) }.joined())
}

guard try git(["rev-parse", "--is-shallow-repository"]) == Data("false\n".utf8) else {
    fatalError("turn version generation requires complete git history")
}
let objects = String(decoding: try git(["rev-list", "--objects", "--all", "--", source]), as: UTF8.self)
var shipped: [Int64: Set<String>] = [:]
for line in objects.split(separator: "\n") where line.hasSuffix(" " + source) {
    let object = String(line.split(separator: " ")[0])
    let body = try identity(git(["cat-file", "blob", object]))
    shipped[body.version, default: []].insert(body.digest)
}
// This is the upgrade table: the bundled body itself needs no installation.
let current = try identity(Data(contentsOf: repo.appendingPathComponent(source)))
shipped[current.version]?.remove(current.digest)
if shipped[current.version]?.isEmpty == true { shipped.removeValue(forKey: current.version) }
var lines = [
    "// Blueprint: | `TurnPart+ShippedBodies.swift` | `TurnPart.shipped`: generated prior shipped turn-body versions and digests from git history; the currently bundled body is not an upgrade candidate |",
    "// Generated by script/generate_turn_part_versions.swift; do not hand-edit.",
    "// Bundled body (not an upgrade): version \(current.version), sha256 \(current.digest).",
    "extension TurnPart {",
    "    static let shipped: [Int64: Set<String>] = [",
]
for version in shipped.keys.sorted() {
    lines.append("        \(version): [" + shipped[version]!.sorted().map { "\"" + $0 + "\"" }.joined(separator: ", ") + "],")
}
lines += ["    ]", "}", ""]
let generated = Data(lines.joined(separator: "\n").utf8)
let existing = FileManager.default.fileExists(atPath: destination.path) ? try Data(contentsOf: destination) : nil
if check {
    guard generated == existing else {
        fputs("[turn versions] generated table differs; run swift script/generate_turn_part_versions.swift\n", stderr)
        exit(1)
    }
} else if generated != existing {
    try generated.write(to: destination, options: .atomic)
}
print("[turn versions] \(check ? "checked" : "generated") \(shipped.values.reduce(0) { $0 + $1.count }) prior bodies across \(shipped.count) versions")
